-- เส้นแบ่งใหม่ของสิ่งที่ระบบจับได้จากบทสนทนา (9 ก.ย. 2569)
-- เจ้าของงานสั่งไว้ว่า: "สั่งแล้วมีคนรับ" = งาน · "ถามแล้วได้คำตอบ" = แค่รู้ไว้ ห้ามเข้าคิวงาน
--
-- เดิมทุกอย่างที่จับได้กลายเป็นรายการรอยืนยัน แล้วไม่มีใครมาดู ค้าง 26 รายการใน 6 วัน
-- แล้วของเก่าก็ย้อนไปโผล่ในสรุปประจำวันในฐานะ "งานปัจจุบัน" ทำให้สรุปมั่ว
-- NOTE คือช่องสำหรับสิ่งที่ควรจำแต่ไม่ใช่คิวงานของใคร ค้นเจอได้ แต่ไม่ไปรบกวนใคร

alter table events drop constraint if exists events_type_check;
alter table events add constraint events_type_check
  check (type in ('TASK', 'NOTE', 'DECISION', 'DEADLINE'));

-- ของเก่าที่ค้างอยู่: เก็บไว้เป็นความรู้ตามที่สั่ง ไม่ใช่ลบทิ้ง และไม่ใช่คิวงานอีกต่อไป
-- TASK ที่ค้างอยู่ก็ถูกจับด้วยเกณฑ์เดิมที่กว้างเกินไป (ไม่ได้ตรวจว่ามีคนรับปาก) จึงถือเป็นความรู้เหมือนกัน
update events set type = 'NOTE' where status = 'NEW';
