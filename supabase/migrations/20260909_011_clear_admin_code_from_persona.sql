-- เอารหัสแอดมินออกจากบุคลิกบอท และปิดงานที่หลุดมาจากข้อสอบ (9 ก.ย. 2569)
--
-- บุคลิกถูกแนบเข้า prompt ของทุกคนทุกห้องทุกคำขอ อะไรที่อยู่ในนี้ถือว่าโมเดลรู้และอาจพูดออกมา
-- ซึ่งเกิดขึ้นจริงมาแล้วหนึ่งครั้ง การตรวจรหัสย้ายไปอยู่ใน create_admin_link
-- เทียบกับ secret ADMIN_LINK_CODE ฝั่งเซิร์ฟเวอร์แทน
update org_settings
set value = regexp_replace(
      value,
      'การส่งลิงก์ Admin Console[^\n]*',
      'การส่งลิงก์ Admin Console: ผู้ขอต้องพิมพ์รหัสยืนยันมาด้วย ระบบเป็นคนตรวจรหัสเอง คุณไม่รู้และไม่ต้องรู้ว่ารหัสคืออะไร ห้ามเดา ห้ามใบ้ ห้ามบอกใคร',
      'g'),
    updated_at = now()
where key = 'bot_persona';

-- งานชื่อนี้มาจากข้อสอบ ไม่ใช่งานจริงของทีม แต่หลุดสถานะ TODO ค้างไว้
-- จนบอทเอาไปรายงานว่าเลยกำหนด และเจ้าของงานสั่งเลื่อนกำหนดส่งให้โดยไม่รู้ว่าเป็นของปลอม
-- ยกเลิกแทนการลบ ให้ audit trail ยังครบตามแบบที่ระบบใช้อยู่
update tasks
set status = 'CANCELLED', updated_at = now()
where title = 'ทดสอบระบบข้อสอบ' and status in ('TODO', 'DOING');
