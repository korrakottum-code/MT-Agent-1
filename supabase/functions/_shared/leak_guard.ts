// เช่นรายงานผลแอดที่มีหัวข้อ "วิเคราะห์:" อยู่จริง ไม่ควรโดนตัดทิ้ง

// เจอตัวเดียวก็ใช่ — คำตอบถึงคนไม่มีเหตุผลจะพูดถึงสิ่งเหล่านี้เลย
const STRONG: RegExp[] = [
  /system\s*prompt|SYSTEM_RULES/i,
  /ห้ามใช้\s*markdown|เรื่อง\s*markdown|ตรวจเช็ค?\s*markdown/i,
  /ตามกฎของระบบ/,
  // คุยกับคนจะเรียกพี่ คุณ หรือชื่อเล่น ไม่มีใครเรียกคนที่คุยด้วยว่า "ผู้ใช้"
  /^\s*ผู้ใช้(ต้องการ|ถาม|สั่ง|ขอ|พิมพ์|บอก)/m,
];

// เจอตัวเดียวอาจเป็นคำตอบปกติ ต้องสองตัวขึ้นไปถึงนับ
const WEAK: RegExp[] = [
  /^\s*(วิเคราะห์|analysis|reasoning|thinking)\s*:/im,
  /^\s*ตามกฎ\s*:/m,
  /^\s*กฎ\s*(ข้อ\s*)?\d+(\.\d+)*\s/m,
  /^\s*เขียน(ตอบ|ข้อความ)(ให้|อย่าง)/m,
  /^\s*ถ้า(พูด|สั่ง)กับแงว/m,
  /tool\s*(หรือ|หรือว่า)?\s*สิทธิ์|มี\s*tool|ไม่มี\s*tool/i,
];

export function looksLikeLeakedReasoning(text: string): boolean {
  if (STRONG.some((r) => r.test(text))) return true;
  return WEAK.filter((r) => r.test(text)).length >= 2;
}

