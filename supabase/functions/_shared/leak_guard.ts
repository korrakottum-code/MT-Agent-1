// ชื่อเครื่องมือทุกตัวมีขีดล่าง จับเป็นคำทั้งคำ ไม่ไปโดนส่วนหนึ่งของคำอื่นหรือลิงก์

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const wordRe = (name: string, flags = "") => new RegExp(`(?<![A-Za-z0-9_/=?&.-])${escapeRe(name)}(?![A-Za-z0-9_])`, flags);

export function scrubToolNames(text: string, names: string[]): { text: string; bare: string[] } {
  const known = names.filter((n) => n.includes("_"));
  if (!known.length) return { text, bare: [] };
  const alt = known.map(escapeRe).sort((a, b) => b.length - a.length).join("|");
  // วงเล็บที่ข้างในมีแต่ชื่อเครื่องมือ คั่นด้วยจุลภาค ทับ หรือ "และ" ลบทั้งวงเล็บพร้อมช่องว่างข้างหน้า
  const paren = new RegExp(
    `[ \\t]*[(（]\\s*\`?(?:${alt})\`?(?:\\s*(?:,|/|และ|หรือ)\\s*\`?(?:${alt})\`?)*\\s*[)）]`,
    "g",
  );
  let out = text.replace(paren, "");
  // ชื่อในเครื่องหมายโค้ด เหลือแต่ชื่อเปล่า ไว้ให้รอบเขียนใหม่จัดการต่อ
  out = out.replace(new RegExp("`(" + alt + ")`", "g"), "$1");
  const bare = known.filter((n) => wordRe(n).test(out));
  return { text: out, bare };
}

