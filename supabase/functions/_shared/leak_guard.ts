// รอบเขียนใหม่ล่ม ลบชื่อเปล่าทิ้งดีกว่าส่งชื่อฟังก์ชันออกไป
export function dropToolNames(text: string, names: string[]): string {
  let out = text;
  for (const n of names) {
    out = out.replace(new RegExp(`(?:ด้วย|ใช้|ผ่าน)?\\s*(?:คำสั่ง|ฟังก์ชัน|เครื่องมือ|tool)?\\s*${wordRe(n).source}`, "g"), "");
  }
  return out.replace(/[ \t]{2,}/g, " ").replace(/[ \t]+$/gm, "");
}
